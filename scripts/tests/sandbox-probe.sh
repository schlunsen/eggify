#!/bin/bash
# Runs everyday developer commands and prints one result line each. Prints no file contents.
cd "$(dirname "$0")"
t() { perl -e 'alarm shift; exec @ARGV' "$@"; }
run() { # label, command...
  local label=$1; shift
  local out; out=$(t 40 bash -c "$*" 2>&1); local rc=$?
  printf '%-34s exit=%-3s %s\n' "$label" "$rc" "$(printf '%s' "$out" | tr '\n' ' ' | tail -c 230)"
}
run "write in project"            'echo x > scratch.txt && rm scratch.txt && echo ok'
run "write in /tmp"               'echo x > /tmp/eggify-probe.$$ && rm /tmp/eggify-probe.$$ && echo ok'
run "write in home"               'echo x > ~/eggify-probe-home.$$ && rm ~/eggify-probe-home.$$ && echo ok'
run "write on Desktop"            'echo x > ~/Desktop/eggify-probe.$$ && rm ~/Desktop/eggify-probe.$$ && echo ok'
run "read ~/.ssh (list only)"     'ls ~/.ssh >/dev/null && echo "readable: $(ls ~/.ssh | wc -l | tr -d " ") entries"'
run "read ssh private key"        'for f in ~/.ssh/id_*; do case $f in *.pub) ;; *) head -c 1 "$f" >/dev/null && echo "readable: $(basename $f)";; esac; done'
run "read ~/.aws"                 'ls ~/.aws >/dev/null && echo readable'
run "read ~/.config/gh"           'test -r ~/.config/gh/hosts.yml && echo readable'
run "read ~/.zsh_history"         'head -c 1 ~/.zsh_history >/dev/null && echo readable'
run "read release.env"            'head -c 1 ~/.config/eggify/release.env >/dev/null && echo readable'
run "read Eggify api key"         'head -c 1 ~/.claude/eggify/.secret >/dev/null && echo readable'
run "read Eggify database"        'head -c 1 ~/.claude/eggify/eggify.db >/dev/null && echo readable'
run "read Claude credentials"     'head -c 1 ~/.claude/.credentials.json >/dev/null && echo readable'
run "keychain: list"              'security list-keychains >/dev/null && echo ok'
run "keychain: find a password"   'security find-generic-password -s "Claude Code-credentials" >/dev/null 2>&1 && echo "item metadata readable" || echo "not readable"'
run "env has provider keys"       'env | grep -c -E "^(ANTHROPIC_API_KEY|OPENAI_API_KEY|EGGIFY_API_KEY|CLAUDE_CODE_OAUTH_TOKEN)=" '
run "env secret-looking names"    'env | grep -E "(TOKEN|SECRET|PASSWORD|API_KEY)=" | cut -d= -f1 | tr "\n" " "'
run "git status"                  'git status --short | wc -l'
run "git commit"                  'echo "// $(date +%s)" >> main.go && git add -A && git -c user.name=probe -c user.email=p@example.com commit -q -m probe && echo committed'
run "git config (write)"          'git config user.name probe && echo written'
run "git ls-remote https github"  'git ls-remote https://github.com/google/uuid HEAD | cut -c1-12'
run "git ls-remote ssh github"    'GIT_SSH_COMMAND="ssh -o BatchMode=yes -o ConnectTimeout=8" git ls-remote git@github.com:google/uuid.git HEAD | cut -c1-12'
run "gh auth status"              'gh auth status 2>&1 | grep -c "Logged in"'
run "gh api (rate_limit)"         'gh api rate_limit --jq .rate.limit'
run "go build"                    'go build ./... && echo built'
run "go test"                     'go test ./... 2>&1 | tail -1'
run "go mod download"             'go mod download && echo ok'
run "npm install"                 'npm install --no-audit --no-fund 2>&1 | tail -1'
run "npx one-off"                 'npx --yes cowsay@1.6.0 hi 2>&1 | tail -1'
run "uv pip install"              'uv venv -q .venv 2>&1 | tail -1; uv pip install -q --python .venv requests 2>&1 | tail -1; echo done'
run "pip (python3 -m venv)"       'python3 -m venv .venv2 && .venv2/bin/pip install -q idna 2>&1 | tail -1; echo done'
run "cargo --version"             'cargo --version'
run "brew --version"              'brew --version | head -1'
run "xcodebuild -version"         'xcodebuild -version | head -1'
run "swift --version"             'swift --version 2>&1 | head -1'
run "docker ps"                   'docker ps --format "{{.Names}}" | wc -l'
run "curl allowlisted (github)"   'curl -sS -m 10 -o /dev/null -w "%{http_code}" https://api.github.com/zen'
run "curl other site"             'curl -sS -m 10 -o /dev/null -w "%{http_code}" https://example.com'
run "curl npm registry"           'curl -sS -m 10 -o /dev/null -w "%{http_code}" https://registry.npmjs.org/left-pad'
run "curl crates.io"              'curl -sS -m 10 -o /dev/null -w "%{http_code}" https://crates.io/api/v1/crates/serde'
run "curl raw.githubusercontent"  'curl -sS -m 10 -o /dev/null -w "%{http_code}" https://raw.githubusercontent.com/google/uuid/master/README.md'
run "curl Eggify on localhost"    'curl -sS -m 5 -o /dev/null -w "%{http_code}" http://127.0.0.1:3335/api/health'
run "dev server: start + fetch"   'python3 -m http.server 8765 >/dev/null 2>&1 & sleep 2; curl -sS -m 5 -o /dev/null -w "%{http_code}" http://127.0.0.1:8765/; kill %1 2>/dev/null'
run "DNS lookup"                  'dig +short +time=3 +tries=1 example.com | head -1'
run "open an app"                 'open -g -a Calculator 2>&1 && echo opened && osascript -e "quit app \"Calculator\"" 2>/dev/null'
run "osascript"                   'osascript -e "return 1+1"'
run "ps of other processes"       'ps ax | wc -l'
run "edit .git/hooks"             'echo x > .git/hooks/pre-commit && echo written'
run "edit .mcp.json"              'echo "{}" > .mcp.json && echo written'
run "edit ~/.zshrc"               'echo "# probe" >> ~/.zshrc.eggify-probe && rm ~/.zshrc.eggify-probe && echo written'
run "write ~/Library/LaunchAgents" 'echo x > ~/Library/LaunchAgents/eggify-probe.plist && rm ~/Library/LaunchAgents/eggify-probe.plist && echo written'
