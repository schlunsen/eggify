//! `testdata/vectors.json`: deterministic vectors for the Go side (internal/license, internal/relay).
//!
//! Regenerate with:
//!   cargo test --test fixture -- --ignored write_fixture
//! `fixture_is_current` fails if the file no longer matches what this server produces.

mod common;

use axum::http::StatusCode;
use base64::engine::general_purpose::{STANDARD, URL_SAFE_NO_PAD};
use base64::Engine;
use common::*;
use ed25519_dalek::pkcs8::EncodePrivateKey;
use ed25519_dalek::SigningKey;
use eggify_license::crypto::{self, TokenPayload};
use eggify_license::{db, serial};
use serde_json::{json, Value};
use std::path::PathBuf;

const SERVER_SEED: &str = "9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60";
const INSTALL_SEED: &str = "4ccd089b28ff96da9db6c346ec114e0f5b8a319f35aba624da8cf6ed4fb8a6fb";
const TIMESTAMP: i64 = 1_792_000_000;
const SERIAL_TYPED: &str = "EGG-7H3K9-Q2M4X-8R6T1-V5N0T";
const SERIAL_ID: &str = "8f6c2a52-3b1e-4c8e-9d7a-1f2e3d4c5b6a";
const MACHINE: &str = "Dev's MacBook Pro";
const APP_VERSION: &str = "2.18.0";
/// Relay subscription ends 10 days after issue: inside the token's 30 days, so the vector
/// shows the relay refusing a token that is otherwise still valid.
const RELAY_UNTIL: i64 = TIMESTAMP + 10 * 86400;

fn seed(hex_str: &str) -> [u8; 32] {
    hex::decode(hex_str).unwrap().try_into().unwrap()
}

fn path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("testdata/vectors.json")
}

fn build() -> Value {
    let server = SigningKey::from_bytes(&seed(SERVER_SEED));
    let install = Client::from_seed(seed(INSTALL_SEED));
    let norm = serial::normalise(SERIAL_TYPED).unwrap();

    let req = |action: &str, s: &str| {
        let msg = install.message(action, TIMESTAMP, s);
        (msg, install.sign(action, TIMESTAMP, s))
    };
    let (act_msg, act_sig) = req("activate", &norm);
    let (renew_msg, renew_sig) = req("renew", "");
    let (deact_msg, deact_sig) = req("deactivate", "");

    let payload = TokenPayload::new(
        SERIAL_ID,
        &install.install_id(),
        "standard",
        MACHINE,
        Some(RELAY_UNTIL),
        TIMESTAMP,
    );
    let token = crypto::sign_token(&server, &payload);
    let payload_json = |t: &str| {
        String::from_utf8(
            URL_SAFE_NO_PAD
                .decode(t.split('.').next().unwrap())
                .unwrap(),
        )
        .unwrap()
    };
    let app_only = TokenPayload::new(
        SERIAL_ID,
        &install.install_id(),
        "standard",
        MACHINE,
        None,
        TIMESTAMP,
    );
    let app_only_token = crypto::sign_token(&server, &app_only);

    json!({
        "comment": "Deterministic vectors for docs/licensing-protocol.md. Generated by services/license-server/tests/fixture.rs; test keys only, never used in production.",
        "server_key": {
            "seed_hex": SERVER_SEED,
            "public_key": STANDARD.encode(server.verifying_key().as_bytes()),
            "pkcs8_pem": server.to_pkcs8_pem(ed25519_dalek::pkcs8::spki::der::pem::LineEnding::LF).unwrap().to_string(),
        },
        "install_key": {
            "seed_hex": INSTALL_SEED,
            "install_key": install.install_key(),
            "install_id": install.install_id(),
        },
        "serials": {
            "vectors": [
                {"body": "0000000000000000000", "serial": "EGG-00000-00000-00000-00000"},
                {"body": "ABCDEFGHJKMNPQRSTVW", "serial": "EGG-ABCDE-FGHJK-MNPQR-STVWT"},
                {"body": "ZZZZZZZZZZZZZZZZZZZ", "serial": "EGG-ZZZZZ-ZZZZZ-ZZZZZ-ZZZZ0"},
                {"body": "7H3K9Q2M4X8R6T1V5N0", "serial": "EGG-7H3K9-Q2M4X-8R6T1-V5N0T"},
            ],
            "normalise": [
                {"input": "egg 7h3k9-q2m4x-8r6t1-v5n0t", "normalised": "7H3K9Q2M4X8R6T1V5N0T"},
                {"input": "7h3k9_q2m4x_8r6tl_v5nOt", "normalised": "7H3K9Q2M4X8R6T1V5N0T"},
                {"input": "EGG-7H3K9-Q2M4X-8R6T1-V5N0A", "normalised": null},
            ],
            "sha256_hex": serial::hash(&norm),
            "hint": serial::hint(&norm),
        },
        "activate_request": {
            "body": {
                "serial": SERIAL_TYPED,
                "install_key": install.install_key(),
                "timestamp": TIMESTAMP,
                "signature": act_sig,
                "machine": MACHINE,
                "app_version": APP_VERSION,
            },
            "message": act_msg,
        },
        "renew_request": {
            "body": { "install_key": install.install_key(), "timestamp": TIMESTAMP, "signature": renew_sig, "app_version": APP_VERSION },
            "message": renew_msg,
        },
        "deactivate_request": {
            "body": { "install_key": install.install_key(), "timestamp": TIMESTAMP, "signature": deact_sig },
            "message": deact_msg,
        },
        "token": {
            "token": token,
            "payload_json": payload_json(&token),
            "payload": serde_json::to_value(&payload).unwrap(),
            "install_id": install.install_id(),
            "valid_at": TIMESTAMP + 1,
            "expired_at": payload.expires_at,
            "relay_admits_at": RELAY_UNTIL - 1,
            "relay_refuses_at": RELAY_UNTIL,
        },
        "token_without_relay": {
            "token": app_only_token,
            "payload_json": payload_json(&app_only_token),
            "payload": serde_json::to_value(&app_only).unwrap(),
            "install_id": install.install_id(),
            "valid_at": TIMESTAMP + 1,
        },
    })
}

#[test]
#[ignore]
fn write_fixture() {
    let s = serde_json::to_string_pretty(&build()).unwrap() + "\n";
    std::fs::write(path(), s).unwrap();
}

#[test]
fn fixture_is_current() {
    let file: Value = serde_json::from_str(
        &std::fs::read_to_string(path()).expect("testdata/vectors.json exists"),
    )
    .unwrap();
    assert_eq!(
        file,
        build(),
        "testdata/vectors.json is stale; regenerate it (see top of tests/fixture.rs)"
    );
}

#[test]
fn fixture_verifies_independently() {
    let f: Value = serde_json::from_str(&std::fs::read_to_string(path()).unwrap()).unwrap();
    let server_pub: [u8; 32] = STANDARD
        .decode(f["server_key"]["public_key"].as_str().unwrap())
        .unwrap()
        .try_into()
        .unwrap();
    let server_vk = ed25519_dalek::VerifyingKey::from_bytes(&server_pub).unwrap();
    let pem_key =
        crypto::load_signing_key_from_pem(f["server_key"]["pkcs8_pem"].as_str().unwrap()).unwrap();
    assert_eq!(pem_key.verifying_key(), server_vk);

    let ik = f["install_key"]["install_key"].as_str().unwrap();
    let ivk = crypto::parse_install_key(ik).unwrap();
    assert_eq!(crypto::install_id(&ivk), f["install_key"]["install_id"]);

    for name in ["activate_request", "renew_request", "deactivate_request"] {
        let r = &f[name];
        let b = &r["body"];
        let action = name.trim_end_matches("_request");
        let s = if action == "activate" {
            serial::normalise(b["serial"].as_str().unwrap()).unwrap()
        } else {
            String::new()
        };
        let ts = b["timestamp"].as_i64().unwrap();
        assert_eq!(
            crypto::request_message(action, ik, ts, &s),
            r["message"].as_str().unwrap()
        );
        crypto::verify_request(
            &ivk,
            action,
            ik,
            ts,
            &s,
            b["signature"].as_str().unwrap(),
            ts,
        )
        .unwrap();
    }

    let t = &f["token"];
    let p = crypto::verify_token(
        &server_vk,
        t["token"].as_str().unwrap(),
        t["install_id"].as_str().unwrap(),
        t["valid_at"].as_i64().unwrap(),
    )
    .unwrap();
    assert_eq!(serde_json::to_value(&p).unwrap(), t["payload"]);
    assert_eq!(p.features, vec!["app", "relay"]);
    assert!(p.admits_relay(t["relay_admits_at"].as_i64().unwrap()));
    assert!(!p.admits_relay(t["relay_refuses_at"].as_i64().unwrap()));
    // Still a valid app license when the relay stops.
    crypto::verify_token(
        &server_vk,
        t["token"].as_str().unwrap(),
        t["install_id"].as_str().unwrap(),
        t["relay_refuses_at"].as_i64().unwrap(),
    )
    .unwrap();
    let t2 = &f["token_without_relay"];
    let p2 = crypto::verify_token(
        &server_vk,
        t2["token"].as_str().unwrap(),
        t2["install_id"].as_str().unwrap(),
        t2["valid_at"].as_i64().unwrap(),
    )
    .unwrap();
    assert_eq!(serde_json::to_value(&p2).unwrap(), t2["payload"]);
    assert!(t2["payload"]["relay_until"].is_null());
    assert_eq!(p2.features, vec!["app"]);
    assert!(!p2.admits_relay(t2["valid_at"].as_i64().unwrap()));
    assert_eq!(
        crypto::verify_token(
            &server_vk,
            t["token"].as_str().unwrap(),
            t["install_id"].as_str().unwrap(),
            t["expired_at"].as_i64().unwrap()
        ),
        Err(crypto::TokenError::Expired)
    );
}

/// The fixture's activate request is accepted by the real handler (clock pinned to its timestamp).
#[tokio::test]
async fn fixture_request_activates_against_the_server() {
    let f: Value = serde_json::from_str(&std::fs::read_to_string(path()).unwrap()).unwrap();
    let h = Harness::with_clock(TIMESTAMP);
    let norm = serial::normalise(SERIAL_TYPED).unwrap();
    db::insert_serial(
        &h.admin_db(),
        &serial::hash(&norm),
        &serial::hint(&norm),
        "standard",
        3,
        "",
        Some(RELAY_UNTIL),
        0,
    )
    .unwrap();
    let (st, v) = h.post("/v1/activate", &f["activate_request"]["body"]).await;
    assert_eq!(st, StatusCode::OK, "{v}");
    let token = v["token"].as_str().unwrap();
    let p = crypto::verify_token(
        &h.server_key.verifying_key(),
        token,
        f["install_key"]["install_id"].as_str().unwrap(),
        TIMESTAMP,
    )
    .unwrap();
    assert_eq!(
        (p.relay_until, p.features),
        (
            Some(RELAY_UNTIL),
            vec!["app".to_string(), "relay".to_string()]
        )
    );
    assert_eq!(v["expires_at"], TIMESTAMP + 30 * 86400);
    let (st, _) = h.post("/v1/renew", &f["renew_request"]["body"]).await;
    assert_eq!(st, StatusCode::OK);
    let (st, v) = h
        .post("/v1/deactivate", &f["deactivate_request"]["body"])
        .await;
    assert_eq!((st, v), (StatusCode::OK, json!({})));
}
